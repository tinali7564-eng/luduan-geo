// robots.txt 解析（遵循 RFC 9309：分组、最长匹配、Allow 优先、空 Disallow 表示全部允许）

export function parseRobots(txt) {
  const groups = []; // { agents: [], rules: [{type, path}] }
  const sitemaps = [];
  if (!txt) return { groups, sitemaps };
  let current = null;
  let lastWasAgent = false;
  for (let raw of String(txt).split(/\r?\n/)) {
    const hash = raw.indexOf('#');
    if (hash !== -1) raw = raw.slice(0, hash);
    const line = raw.trim();
    if (!line) continue;
    const colon = line.indexOf(':');
    if (colon === -1) continue;
    const key = line.slice(0, colon).trim().toLowerCase();
    const value = line.slice(colon + 1).trim();
    if (key === 'user-agent') {
      if (!current || !lastWasAgent) { current = { agents: [], rules: [] }; groups.push(current); }
      current.agents.push(value.toLowerCase());
      lastWasAgent = true;
    } else if (key === 'allow' || key === 'disallow') {
      if (current) current.rules.push({ type: key, path: value });
      lastWasAgent = false;
    } else if (key === 'sitemap') {
      if (value) sitemaps.push(value);
    } else {
      lastWasAgent = false;
    }
  }
  return { groups, sitemaps };
}

function rulesFor(parsed, botToken) {
  const token = botToken.toLowerCase();
  const specific = parsed.groups.filter(g => g.agents.includes(token));
  if (specific.length) return { rules: specific.flatMap(g => g.rules), matched: 'specific' };
  const wildcard = parsed.groups.filter(g => g.agents.includes('*'));
  if (wildcard.length) return { rules: wildcard.flatMap(g => g.rules), matched: 'wildcard' };
  return { rules: [], matched: 'none' };
}

function patternToRegex(p) {
  const anchored = p.endsWith('$');
  const body = (anchored ? p.slice(0, -1) : p).split('*').map(s => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('.*');
  return new RegExp('^' + body + (anchored ? '$' : ''));
}

export function isAllowed(rules, path) {
  let best = null;
  for (const r of rules) {
    if (!r.path) continue; // 空 Disallow = 不限制
    let decoded = r.path;
    try { decoded = decodeURI(r.path); } catch { /* 保持原样 */ }
    if (!patternToRegex(decoded).test(path)) continue;
    const len = decoded.replace(/\*/g, '').length;
    if (!best || len > best.len || (len === best.len && r.type === 'allow')) best = { len, type: r.type, path: r.path };
  }
  return { allowed: !best || best.type === 'allow', rule: best };
}

/**
 * 判断某个 AI 爬虫对站点根目录与指定页面的可访问状态
 * status: allowed | partial | blocked | page_blocked
 */
export function botAccess(parsed, botToken, pagePath = '/') {
  const { rules, matched } = rulesFor(parsed, botToken);
  const root = isAllowed(rules, '/');
  const page = isAllowed(rules, pagePath || '/');
  const disallows = rules.filter(r => r.type === 'disallow' && r.path);
  let status = 'allowed';
  if (!root.allowed) status = 'blocked';
  else if (!page.allowed) status = 'page_blocked';
  else if (disallows.length && matched === 'specific') status = 'partial';
  return {
    status,
    allowed: status !== 'blocked' && status !== 'page_blocked',
    matched,
    explicit: matched === 'specific',
    disallowSample: disallows.slice(0, 3).map(r => r.path),
  };
}

// 在保留站点原有规则的前提下，生成加入 AI 爬虫分组后的 robots.txt
export function mergeAiRules(existing, aiBlock, origin, locale = 'zh') {
  const en = locale === 'en';
  const parsed = parseRobots(existing || '');
  const aiTokens = new Set(aiBlock.flatMap(g => g.agents.map(a => a.toLowerCase())));
  const lines = [];
  if (existing && existing.trim()) {
    // 原样保留与 AI 爬虫无关的分组
    const keep = parsed.groups.filter(g => !g.agents.every(a => aiTokens.has(a)));
    lines.push(en ? '# ===== Your existing rules (kept as-is) =====' : '# ===== 以下为站点原有规则（已保留） =====');
    for (const g of keep) {
      for (const a of g.agents) lines.push(`User-agent: ${a === '*' ? '*' : a}`);
      for (const r of g.rules) lines.push(`${r.type === 'allow' ? 'Allow' : 'Disallow'}: ${r.path}`);
      lines.push('');
    }
  } else {
    lines.push('User-agent: *', 'Allow: /', '');
  }
  lines.push(en ? '# ===== AI crawler policy (generated by DailyToolbox GEO) =====' : '# ===== AI 爬虫访问策略（由 DailyToolbox GEO 生成） =====');
  // 注意：一旦为某爬虫单独建组，它就不再遵守 “User-agent: *” 的规则。
  // 因此“放行”分组会继承站点通配规则里的 Disallow（如 /admin），只放开公开内容。
  const wildcardRules = parsed.groups.filter(g => g.agents.includes('*')).flatMap(g => g.rules).filter(r => r.path);
  for (const g of aiBlock) {
    if (g.comment) lines.push(`# ${g.comment}`);
    for (const a of g.agents) lines.push(`User-agent: ${a}`);
    if (!g.allow) lines.push('Disallow: /');
    else if (wildcardRules.length) for (const r of wildcardRules) lines.push(`${r.type === 'allow' ? 'Allow' : 'Disallow'}: ${r.path}`);
    else lines.push('Allow: /');
    lines.push('');
  }
  const sitemaps = parsed.sitemaps.length ? parsed.sitemaps : [`${origin}/sitemap.xml`];
  for (const s of [...new Set(sitemaps)]) lines.push(`Sitemap: ${s}`);
  return lines.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}
